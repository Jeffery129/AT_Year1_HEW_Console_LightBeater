#include "main.h"
#include "game.h"

// Windows の時間APIを使うため（VS なら winmm.lib のリンクが必要）
#include <windows.h>
#include <mmsystem.h>
#pragma comment(lib, "winmm.lib")

// このファイル内の関数プロトタイプ宣言：main より後で定義しても呼べるようにする
void Initialize(void);
void Finalize(void);
void Update(void);
void Draw(void);
#ifdef _DEBUG
void DisplayFps(void);
#endif

int fpsCount = 0;	// 画面表示用の FPS 値（0.5 秒ごとに更新）

/* --------------------------------------------------------------------------
 * 【超詳細】最小構成ゲームループの考え方（約60FPS）
 *
 * ■時間管理（Windows/MMタイマー）
 *	- timeBeginPeriod(1): OSのタイマ精度を1msに上げ、timeGetTime()の刻みを細かくする。
 *	 → 「前回更新時刻」から「現在時刻」までの差が 1000/60 ms（約16.6ms）以上なら
 *		1フレーム進める（Update→Drawを1回実行）という判断がしやすくなる。
 *
 * ■フレーム処理の順番
 *	1) UpdateGame(): 入力→プレイヤ移動→重力→当たり判定（物理）などの状態更新。
 *	2) DrawGame(): 背景（床）→前景（プレイヤ）の順で描画。
 *		- 「背景→前景」にする理由：
 *		文字ベース描画では、背景の全角ブロックが前景（プレイヤ）を上書きしてしまうと
 *		プレイヤが消える。逆順にしないためにも、背景を先に描く。
 *		- また、各描画では「前フレームの絵を消してから今フレームの絵を描く」という
 *		“残像対策”を組み込む（床は DrawField(), プレイヤは DrawPlayer()）。
 *
 * ■FPS表示（任意）
 *	- 0.5秒ごとに描画回数からFPSを計算し、画面左上に "FPS:xx" と上書き表示。
 *
 * ■ループ終了条件
 *	- inport(PK_ESC) が押されるまで継続。終了時にカーソルを通常表示へ戻し、後処理。
 * -------------------------------------------------------------------------- */
int main()
{

	/* --------------------------------------------------------------------------
	*　最初に呼び出す
	* -------------------------------------------------------------------------- */
	if (HEWConsoleStartup(0) != 0)
	{
		fprintf(stderr, "Initialization failed.\n");
		HEWConsoleCleanup(0);
		return 1;
	}
	/* --------------------------------------------------------------------------
	* ここまで
	* -------------------------------------------------------------------------- */

	// 時間管理用の変数（ミリ秒単位）
	DWORD lastUpdateTimeMs,	// 前回「更新/描画」した時刻
		lastFpsTimeMs,	// 前回「FPSを再計算」した時刻（0.5秒ごと）
		currentTimeMs;		// 現在時刻
	int frameCount;			// 0.5秒間に何フレーム描けたか（FPS算出用）

	// timeBeginPeriod(1):
	//	Windows の「タイマー分解能」を細かくする（1ms刻みをリクエスト）。終了時は必ず timeEndPeriod で元へ戻す。
	//	これにより timeGetTime() の精度が上がり、等間隔処理がしやすくなります。
	timeBeginPeriod(1);

	// 初期値：現在時刻を取得し、2つの基準時刻（更新/描画用・FPS用）を揃える
	lastUpdateTimeMs = lastFpsTimeMs = timeGetTime();
	currentTimeMs = 0;
	frameCount = 0;

	// 作業中はカーソルを消す（NOCURSOR）…画面上の“点滅するカーソル”が邪魔なので非表示
	setcursortype(NOCURSOR);

	// 画面のクリア
	clrscr();

	// ゲーム固有の初期化（プレイヤー／床の準備）
	Initialize();

	// ----------------------------- メインループ ------------------------------
	// ESC キーが押されるまで繰り返す（inport(PK_ESC) は CONIOEX の入力関数）
	do
	{
		// 現在時刻（ミリ秒）を取得
		currentTimeMs = timeGetTime();

		// 0.5秒（500ms）ごとに FPS を再計算して表示値を更新
		if ((currentTimeMs - lastFpsTimeMs) >= 500) {
			// frameCount（直近0.5秒で描けたフレーム数）から 1秒あたりの換算を行う
			// fps = (経過フレーム数) * 1000 / (経過ミリ秒)
			fpsCount = frameCount * 1000 / (currentTimeMs - lastFpsTimeMs);
			lastFpsTimeMs = currentTimeMs;
			frameCount = 0;	// カウンタリセット
		}

		// 約60FPS（16ms相当の周期で Update/Draw）で、「更新→描画」するため、16～17ms ごとに処理を回す
		if ((currentTimeMs - lastUpdateTimeMs) >= (1000 / 60)) {
			// 今回の基準時刻を更新
			lastUpdateTimeMs = currentTimeMs;

			// 物理や入力などの更新
			Update();		// ロジック更新（入力・物理・衝突・接地更新など）

			// 重要：優先度の低いものから描画
			Draw();		// 見た目更新（描画）

			// 0.5秒の枠に何枚描けたかをカウント（FPS算出用）
			frameCount++;	// FPS 計測用にフレーム数をインクリメント

#ifdef _DEBUG
			// 画面左上に「FPS:xx」を上書き表示する（毎フレームのリアルタイム確認）
			DisplayFps();
#endif
		}
	} while (!inport(PK_ESC));// ESC が押されていない間ループ継続、ESCが押されるとループ終了

	// 作業終了：カーソルを戻す
	setcursortype(NORMALCURSOR);	// カーソル表示を元に（終了前）

	// 後処理（動的資源(メモリ)解放など）
	Finalize();

	// タイマー精度(分解能)を元に戻す（副作用を残さない）
	timeEndPeriod(1);

	/* --------------------------------------------------------------------------
	*　main関数の最後に呼び出す
	* -------------------------------------------------------------------------- */
	HEWConsoleCleanup(1);
	/* --------------------------------------------------------------------------
	*　ここまで
	* -------------------------------------------------------------------------- */

	return 0;
}

//-----------------------------------------------------------------------------
// 初期化：ゲーム開始時に1回だけ呼ばれる
//-----------------------------------------------------------------------------
/* --------------------------------------------------------------------------
 * Initialize():
 *	- プレイヤ・床の初期配置や各種パラメータの準備を行う。
 *	- 初期描画が破綻しないよう、各モジュール側で「前フレーム情報」も適切に初期化する。
 * -------------------------------------------------------------------------- */
void Initialize(void)
{
	InitializeGame();		// ゲームシーンの初期化
}

//-----------------------------------------------------------------------------
// 終了処理：ゲーム終了時（mainを抜ける前）に1回だけ呼ばれる
//-----------------------------------------------------------------------------
/* --------------------------------------------------------------------------
 * Finalize():
 *	- 現在は動的リソースなし。将来、音/画像などを追加した場合にここで解放する。
 * -------------------------------------------------------------------------- */
void Finalize(void)
{
	FinalizeGame();		// ゲームシーンの終了処理
}

//-----------------------------------------------------------------------------
// 毎フレームの更新：入力→移動→物理（重力）→衝突判定 など
//-----------------------------------------------------------------------------
/* --------------------------------------------------------------------------
 * UpdateGame():
 *	- 「入力→プレイヤ移動→重力付与→床との当たり判定」までを player.cpp が担当。
 *	- 床の振る舞い（移動/消滅/幅周期/斜面など）は field.cpp が担当。
 *	- それぞれを1フレーム分進める。
 * -------------------------------------------------------------------------- */
void Update(void)
{	// 毎フレーム更新（ロジック）
	UpdateGame();		// ゲームシーンの更新
}

//-----------------------------------------------------------------------------
// 毎フレームの描画：背景（床）→前景（プレイヤー）
//-----------------------------------------------------------------------------
/* --------------------------------------------------------------------------
 * DrawGame():
 *	- 「床→プレイヤ」の順で描画する（残像対策とレイヤ順のため）。
 *	- 床は全角ブロック行や斜面を“前→今→前情報更新”の順で扱い、前フレーム絵を消してから描く。
 *	- プレイヤは直前の座標を記録し、次フレーム冒頭で全角スペース（U+3000）で消す。
 * -------------------------------------------------------------------------- */
void Draw(void)
{	// 毎フレーム描画（見た目）
	DrawGame();		// ゲームシーンの描画
}

//-----------------------------------------------------------------------------
// デバッグ用：FPS表示（画面左上 (1,1) に FPS を出す）
//-----------------------------------------------------------------------------
#ifdef _DEBUG
void DisplayFps(void)
{
	textcolor(LIGHTGREEN);// 明るい緑文字
	gotoxy(1, 1);		// 画面左上（1,1）
	std::cout << "FPS:" << fpsCount << std::flush;// 前面に上書き
	textcolor(WHITE);	// 白文字
}
#endif